// Scans public/symps/products and public/symps/projects and writes
// src/symps/data/assets.generated.ts so the film knows which real photos exist.
import {readdirSync, writeFileSync, existsSync} from 'node:fs';

const exts = /\.(png|webp|jpe?g)$/i;
const list = (dir) => (existsSync(dir) ? readdirSync(dir).filter((f) => exts.test(f)).sort() : []);

const products = {};
for (const f of list('public/symps/products')) products[f.replace(exts, '')] = `symps/products/${f}`;
const projects = list('public/symps/projects').map((f) => `symps/projects/${f}`);

writeFileSync(
	'src/symps/data/assets.generated.ts',
	`// Generated by scripts/scan-symps-assets.mjs — do not edit by hand.\n` +
		`export const PRODUCT_IMAGES: Record<string, string> = ${JSON.stringify(products, null, '\t')};\n` +
		`export const PROJECT_IMAGES: string[] = ${JSON.stringify(projects, null, '\t')};\n`,
);
console.log(`symps assets: ${Object.keys(products).length} product photo(s), ${projects.length} project photo(s)`);
