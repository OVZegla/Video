// Scans public/symps/products and public/symps/projects and writes
// src/symps/data/assets.generated.ts so the film knows which real photos
// exist and their pixel size (used to frame close-ups on the photo).
import {readdirSync, writeFileSync, existsSync, readFileSync} from 'node:fs';

const exts = /\.(png|webp|jpe?g)$/i;
const list = (dir) => (existsSync(dir) ? readdirSync(dir).filter((f) => exts.test(f)).sort() : []);

const size = (path) => {
	const b = readFileSync(path);
	if (b.toString('ascii', 1, 4) === 'PNG') return {w: b.readUInt32BE(16), h: b.readUInt32BE(20)};
	// JPEG: walk the segments to the SOFn marker
	if (b[0] === 0xff && b[1] === 0xd8) {
		let i = 2;
		while (i < b.length) {
			const m = b[i + 1];
			const len = b.readUInt16BE(i + 2);
			if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) return {w: b.readUInt16BE(i + 7), h: b.readUInt16BE(i + 5)};
			i += 2 + len;
		}
	}
	throw new Error(`${path}: use PNG or JPEG`);
};

const products = {};
for (const f of list('public/symps/products')) {
	products[f.replace(exts, '')] = {src: `symps/products/${f}`, ...size(`public/symps/products/${f}`)};
}
const projects = list('public/symps/projects').map((f) => `symps/projects/${f}`);

writeFileSync(
	'src/symps/data/assets.generated.ts',
	`// Generated by scripts/scan-symps-assets.mjs — do not edit by hand.\n` +
		`export type ProductPhoto = {src: string; w: number; h: number};\n` +
		`export const PRODUCT_IMAGES: Record<string, ProductPhoto> = ${JSON.stringify(products, null, '\t')};\n` +
		`export const PROJECT_IMAGES: string[] = ${JSON.stringify(projects, null, '\t')};\n`,
);
console.log(`symps assets: ${Object.keys(products).length} product photo(s), ${projects.length} project photo(s)`);
